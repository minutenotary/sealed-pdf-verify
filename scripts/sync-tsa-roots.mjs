#!/usr/bin/env node
// Regenerates src/tsa-roots.generated.ts from tsa-roots/*.pem so the browser
// build carries the same roots as the CLI. `--check` fails when out of sync.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'tsa-roots');
const target = join(root, 'src', 'tsa-roots.generated.ts');

const files = readdirSync(dir)
  .filter((f) => f.endsWith('.pem'))
  .sort();
const entries = files.map((f) => ({
  name: f.replace(/\.pem$/, ''),
  pem: readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim() + '\n',
}));

let out = '// GENERATED by scripts/sync-tsa-roots.mjs from tsa-roots/*.pem. Do not edit.\n';
out += 'export interface BuiltInRoot {\n  name: string;\n  pem: string;\n}\n\n';
out += 'export const BUILT_IN_TSA_ROOTS: readonly BuiltInRoot[] = [\n';
for (const e of entries) {
  out += `  {\n    name: ${JSON.stringify(e.name)},\n    pem: ${JSON.stringify(e.pem)},\n  },\n`;
}
out += '];\n';

if (process.argv.includes('--check')) {
  let current;
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    current = '';
  }
  if (current !== out) {
    console.error('src/tsa-roots.generated.ts is out of date; run: npm run sync:roots');
    process.exit(1);
  }
  console.log(`tsa roots in sync (${entries.length} certificate file(s))`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${entries.length} certificate file(s))`);
}
